/**
 * Builds src/lib/uzbekistan-map.ts from Natural Earth (public domain) 1:50m admin-0 GeoJSON.
 * Usage: node scripts/build-map.mjs <ne_50m_admin_0_countries.geojson>
 * Projection: equirectangular scaled by cos(mid-latitude), fitted to a 1000-wide viewBox.
 */
import fs from "node:fs";

const src = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
const uz = src.features.find((f) => f.properties.ADM0_A3 === "UZB" || f.properties.ISO_A3 === "UZB");
if (!uz) throw new Error("Uzbekistan not found");

const polys = uz.geometry.type === "Polygon" ? [uz.geometry.coordinates] : uz.geometry.coordinates;
const rings = polys.map((p) => p[0]); // outer rings only
const all = rings.flat();
const lons = all.map((c) => c[0]);
const lats = all.map((c) => c[1]);
const [minLon, maxLon, minLat, maxLat] = [Math.min(...lons), Math.max(...lons), Math.min(...lats), Math.max(...lats)];
const k = Math.cos((((minLat + maxLat) / 2) * Math.PI) / 180);
const W = 1000;
const pad = 20;
const scale = (W - pad * 2) / ((maxLon - minLon) * k);
const H = Math.round((maxLat - minLat) * scale + pad * 2);
const proj = ([lon, lat]) => [pad + (lon - minLon) * k * scale, pad + (maxLat - lat) * scale];

// Drop points closer than 1.5 units to keep the path light.
const simplify = (pts) => pts.filter((p, i) => i === 0 || Math.hypot(p[0] - pts[i - 1][0], p[1] - pts[i - 1][1]) > 1.5);
const d = rings
  .map((r) => simplify(r.map(proj)))
  .filter((r) => r.length > 8)
  .map((r) => "M" + r.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join("L") + "Z")
  .join("");

const cities = {
  tashkent: proj([69.2401, 41.2995]),
  samarkand: proj([66.9597, 39.6542]),
};

const out = `// Generated by scripts/build-map.mjs from Natural Earth 1:50m (public domain). Do not edit by hand.
export const UZ_VIEWBOX = "0 0 ${W} ${H}";
export const UZ_PATH = "${d}";
export const UZ_CITIES = {
  tashkent: { x: ${cities.tashkent[0].toFixed(1)}, y: ${cities.tashkent[1].toFixed(1)} },
  samarkand: { x: ${cities.samarkand[0].toFixed(1)}, y: ${cities.samarkand[1].toFixed(1)} },
} as const;
`;
fs.writeFileSync("src/lib/uzbekistan-map.ts", out);
console.log(`viewBox 0 0 ${W} ${H}; path ${d.length} chars; rings ${rings.length}`, cities);
